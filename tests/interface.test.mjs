import test from 'node:test';
import assert from 'node:assert/strict';
import { parseHTML } from 'linkedom';
const wait=()=>new Promise(r=>setImmediate(r));
const store=()=>{const values=new Map();return {getItem:k=>values.get(k)||null,setItem:(k,v)=>values.set(k,v),removeItem:k=>values.delete(k)};};
test('instructor interface: navigate slides, edit text, format, duplicate, and keep presentation private',async()=>{
  const {window,document}=parseHTML('<html><body><div id="app"></div><div id="toast"></div><div id="modal-root"></div></body></html>');
  Object.assign(globalThis,{document,window,sessionStorage:store(),localStorage:store(),location:{hash:'#demo=1',origin:'http://127.0.0.1:4173',pathname:'/'},history:{replaceState(){}},addEventListener(){},confirm:()=>true});
  const originalInterval=globalThis.setInterval;globalThis.setInterval=()=>0;
  await import('../public/app.js?interface-test');
  globalThis.setInterval=originalInterval;
  const click=async selector=>{const el=document.querySelector(selector);assert(el,selector);el.dispatchEvent(new window.Event('click',{bubbles:true}));await wait();await wait();};
  assert(document.querySelector('#right').textContent.includes('Only you'));
  assert.equal(document.querySelectorAll('.thumb').length,4);
  await click('[data-action="select-slide"][data-id="s1"]');assert(document.querySelector('.slide-title').value.includes('Group 2'));
  const content=document.querySelector('[data-field="content"]');
  Object.defineProperty(content,'innerText',{value:'<img src=x onerror=alert(1)> Our own example.',configurable:true});
  content.dispatchEvent(new window.Event('input',{bubbles:true}));
  await click('[data-action="duplicate"]');
  assert.equal(document.querySelectorAll('.thumb').length,5);
  assert(document.querySelector('.slide-title').value.includes('(copy)'));
  assert.equal(document.querySelectorAll('.slide-paper img').length,0,'student HTML is never interpreted');
  assert(document.querySelector('.block-text').textContent.includes('<img src=x'));
  await click('[data-action="debrief-page"][data-index="1"]');assert(document.querySelector('.debrief-card h3').textContent.includes('disagreement'));
  await click('[data-action="present"]');assert(document.querySelector('.present-view'));
  assert(!document.querySelector('.present-view').textContent.includes('Your facilitation notes'));
  await click('[data-action="close-present"]');assert(!document.querySelector('.present-view'));
  await click('[data-action="delete-slide"]');assert.equal(document.querySelectorAll('.thumb').length,4);
});
